CREATE TABLE vendor_subscriptions (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    public_id   UUID                NOT NULL DEFAULT gen_random_uuid(),
    vendor_id   BIGINT              NOT NULL,
    plan_id     SMALLINT            NOT NULL,
    status      subscription_status NOT NULL DEFAULT 'pending_review',
    price_paid  BIGINT              NOT NULL DEFAULT 0,
    starts_at   TIMESTAMPTZ,
    ends_at     TIMESTAMPTZ,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    review_note TEXT,
    created_at  TIMESTAMPTZ         NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ         NOT NULL DEFAULT now(),
    CONSTRAINT vendor_subscriptions_public_id_key UNIQUE (public_id),
    CONSTRAINT vendor_subscriptions_vendor_fkey   FOREIGN KEY (vendor_id)   REFERENCES vendors(id) ON DELETE CASCADE,
    CONSTRAINT vendor_subscriptions_plan_fkey     FOREIGN KEY (plan_id)     REFERENCES subscription_plans(id),
    CONSTRAINT vendor_subscriptions_reviewer_fkey FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT vendor_subscriptions_price_chk     CHECK (price_paid >= 0),
    CONSTRAINT vendor_subscriptions_window_chk    CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX idx_vendor_subscriptions_vendor ON vendor_subscriptions(vendor_id, created_at DESC);
CREATE UNIQUE INDEX uq_vendor_subscriptions_one_active ON vendor_subscriptions(vendor_id) WHERE status = 'active';

CREATE TRIGGER trg_vendor_subscriptions_updated
    BEFORE UPDATE ON vendor_subscriptions
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TABLE payout_requests (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    public_id        UUID          NOT NULL DEFAULT gen_random_uuid(),
    vendor_id        BIGINT        NOT NULL,
    store_id         BIGINT,
    amount           BIGINT        NOT NULL,                 -- Toman
    status           payout_status NOT NULL DEFAULT 'pending',
    iban             TEXT,
    bank_reference   TEXT,
    requested_by     BIGINT        NOT NULL,
    reviewed_by      BIGINT,
    reviewed_at      TIMESTAMPTZ,
    paid_at          TIMESTAMPTZ,
    rejection_reason TEXT,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT payout_requests_public_id_key UNIQUE (public_id),
    CONSTRAINT payout_requests_vendor_fkey   FOREIGN KEY (vendor_id)    REFERENCES vendors(id) ON DELETE CASCADE,
    CONSTRAINT payout_requests_store_fkey    FOREIGN KEY (store_id)     REFERENCES stores(id) ON DELETE SET NULL,
    CONSTRAINT payout_requests_req_fkey      FOREIGN KEY (requested_by) REFERENCES users(id),
    CONSTRAINT payout_requests_rev_fkey      FOREIGN KEY (reviewed_by)  REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT payout_requests_amount_chk    CHECK (amount > 0),
    CONSTRAINT payout_requests_reject_chk    CHECK (status <> 'rejected' OR rejection_reason IS NOT NULL)
);
CREATE INDEX idx_payout_requests_vendor ON payout_requests(vendor_id, created_at DESC);
CREATE INDEX idx_payout_requests_status ON payout_requests(status, created_at DESC);

CREATE TRIGGER trg_payout_requests_updated
    BEFORE UPDATE ON payout_requests
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
