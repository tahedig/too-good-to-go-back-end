-- Financial management schema synced with Figma Vendor (06) and Admin (07) screens:
-- vendor subscription plans, upgrade requests, and payout/settlement requests.

CREATE TYPE subscription_status AS ENUM ('pending_review', 'active', 'expired', 'rejected', 'cancelled');
CREATE TYPE payout_status       AS ENUM ('pending', 'approved', 'paid', 'rejected');

CREATE TABLE subscription_plans (
    id                SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              TEXT         NOT NULL,
    name_fa           TEXT         NOT NULL,
    monthly_price     BIGINT       NOT NULL DEFAULT 0,       -- Toman
    commission_rate   NUMERIC(5,2) NOT NULL,                 -- % per completed sale
    max_stores        SMALLINT     NOT NULL DEFAULT 1,
    max_active_offers SMALLINT     NOT NULL DEFAULT 5,
    duration_days     SMALLINT     NOT NULL DEFAULT 30,
    is_active         BOOLEAN      NOT NULL DEFAULT true,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT subscription_plans_code_key        UNIQUE (code),
    CONSTRAINT subscription_plans_price_chk       CHECK (monthly_price >= 0),
    CONSTRAINT subscription_plans_commission_chk  CHECK (commission_rate BETWEEN 0 AND 100),
    CONSTRAINT subscription_plans_stores_chk      CHECK (max_stores > 0),
    CONSTRAINT subscription_plans_offers_chk      CHECK (max_active_offers > 0),
    CONSTRAINT subscription_plans_duration_chk    CHECK (duration_days > 0)
);

CREATE TRIGGER trg_subscription_plans_updated
    BEFORE UPDATE ON subscription_plans
    FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

